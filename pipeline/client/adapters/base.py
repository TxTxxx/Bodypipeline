from __future__ import annotations

from pathlib import Path
from typing import Protocol


class CaptureAdapter(Protocol):
    """A start may return started=True, or started=False/pending=True.

    Pending starts are observed through status(), correlated by session_id.
    RECORDING must include the actual recording_started_at wall-clock time;
    stop before recording may return cancelled=True without an episode file.
    A stop may return stopped=False/pending=True while durable saving or offline
    conversion runs. The Client keeps STOPPING and observes status() until
    STOPPED or RECOVERY_REQUIRED; pending saving is never treated as SAVED.
    """

    def health(self) -> dict: ...
    def control_state(self) -> dict: ...
    def set_control_mode(self, mode: str) -> dict: ...
    def remember_fold(self) -> dict: ...
    def enable(self) -> dict: ...
    def reset(self) -> dict: ...
    def start(
        self,
        session_id: str,
        raw_root: Path,
        instruction: str,
        *,
        continuous: bool = False,
    ) -> dict: ...
    def select_next(self, session_id: str, raw_root: Path, instruction: str, *, continuous: bool = False) -> dict:
        """Replace a waiting destination, or schedule it after the active episode."""
        ...
    def retry_conversion(self, session_id: str) -> dict:
        """Requeue a failed conversion, preserving the original recorded data."""
        ...
    def stop(self, session_id: str) -> dict: ...
    def status(self) -> dict: ...
    def joints(self) -> dict: ...
    def frame(self, camera_id: str) -> bytes | None: ...
    def close(self): ...
